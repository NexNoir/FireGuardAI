def prepare_real_firms_features(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """
    Prepare the exact production feature matrix required by the
    approved REAL FIRMS models.

    Important:
        - Input dataframe is NOT modified.
        - Derived encoded columns exist only in the returned dataframe.
        - Output column order is fixed to FEATURE_COLUMNS.
    """

    if not isinstance(dataframe, pd.DataFrame):
        raise TypeError(
            "Input must be a pandas DataFrame."
        )

    if dataframe.empty:
        raise ValueError(
            "Input dataframe is empty."
        )

    missing_base = [
        column
        for column in BASE_REQUIRED_COLUMNS
        if column not in dataframe.columns
    ]

    if missing_base:
        raise ValueError(
            "Required base columns missing: "
            + ", ".join(missing_base)
        )

    working = dataframe.copy()

    # ------------------------------------------------------------------------
    # Numeric base features
    # ------------------------------------------------------------------------

    for column in BASE_REQUIRED_COLUMNS:

        working[column] = pd.to_numeric(
            working[column],
            errors="coerce",
        )

    # ------------------------------------------------------------------------
    # Time features
    # ------------------------------------------------------------------------
    # Prefer existing hour/minute.
    # If unavailable, attempt to derive from common datetime columns.
    # ------------------------------------------------------------------------

    if "hour" not in working.columns or "minute" not in working.columns:

        datetime_column = _find_first_column(
            working,
            [
                "detection_timestamp",
                "acq_datetime",
                "datetime",
                "timestamp",
                "date_time",
            ],
        )

        if datetime_column is not None:

            parsed_datetime = pd.to_datetime(
                working[datetime_column],
                errors="coerce",
            )

            if "hour" not in working.columns:
                working["hour"] = parsed_datetime.dt.hour

            if "minute" not in working.columns:
                working["minute"] = parsed_datetime.dt.minute

        else:

            if "hour" not in working.columns:
                working["hour"] = 0

            if "minute" not in working.columns:
                working["minute"] = 0

    working["hour"] = pd.to_numeric(
        working["hour"],
        errors="coerce",
    )

    working["minute"] = pd.to_numeric(
        working["minute"],
        errors="coerce",
    )

    # ------------------------------------------------------------------------
    # daynight_encoded
    # ------------------------------------------------------------------------

    if "daynight_encoded" in working.columns:

        working["daynight_encoded"] = pd.to_numeric(
            working["daynight_encoded"],
            errors="coerce",
        )

    else:

        daynight_column = _find_first_column(
            working,
            [
                "daynight",
                "day_night",
            ],
        )

        if daynight_column is not None:

            working["daynight_encoded"] = _encode_categorical(
                working[daynight_column],
                {
                    "D": 0,
                    "DAY": 0,
                    "N": 1,
                    "NIGHT": 1,
                },
                default_value=-1,
            )

        else:

            working["daynight_encoded"] = -1

    # ------------------------------------------------------------------------
    # satellite_encoded
    # ------------------------------------------------------------------------

    if "satellite_encoded" in working.columns:

        working["satellite_encoded"] = pd.to_numeric(
            working["satellite_encoded"],
            errors="coerce",
        )

    else:

        satellite_column = _find_first_column(
            working,
            [
                "satellite",
            ],
        )

        if satellite_column is not None:

            working["satellite_encoded"] = _encode_categorical(
                working[satellite_column],
                {
                    "AQUA": 0,
                    "TERRA": 1,
                    "SNPP": 2,
                    "SUOMI NPP": 2,
                    "NOAA-20": 3,
                    "NOAA20": 3,
                    "JPSS-1": 3,
                },
                default_value=-1,
            )

        else:

            working["satellite_encoded"] = -1

    # ------------------------------------------------------------------------
    # instrument_encoded
    # ------------------------------------------------------------------------

    if "instrument_encoded" in working.columns:

        working["instrument_encoded"] = pd.to_numeric(
            working["instrument_encoded"],
            errors="coerce",
        )

    else:

        instrument_column = _find_first_column(
            working,
            [
                "instrument",
            ],
        )

        if instrument_column is not None:

            working["instrument_encoded"] = _encode_categorical(
                working[instrument_column],
                {
                    "MODIS": 0,
                    "VIIRS": 1,
                },
                default_value=-1,
            )

        else:

            working["instrument_encoded"] = -1

    # ------------------------------------------------------------------------
    # type_encoded
    # ------------------------------------------------------------------------

    if "type_encoded" in working.columns:

        working["type_encoded"] = pd.to_numeric(
            working["type_encoded"],
            errors="coerce",
        )

    else:

        type_column = _find_first_column(
            working,
            [
                "type",
                "fire_type",
            ],
        )

        if type_column is not None:

            raw_type = pd.to_numeric(
                working[type_column],
                errors="coerce",
            )

            if raw_type.notna().any():
                working["type_encoded"] = raw_type
            else:
                categories = sorted(
                    _normalize_text(
                        working[type_column]
                    ).unique().tolist()
                )

                category_mapping = {
                    category: index
                    for index, category in enumerate(categories)
                }

                working["type_encoded"] = _encode_categorical(
                    working[type_column],
                    category_mapping,
                    default_value=-1,
                )

        else:

            working["type_encoded"] = -1

    # ------------------------------------------------------------------------
    # season_encoded
    # ------------------------------------------------------------------------
    # Existing encoded column is used when supplied.
    # Otherwise derive from month if available.
    #
    # Encoding:
    #   Winter = 0
    #   Spring = 1
    #   Summer = 2
    #   Autumn = 3
    # ------------------------------------------------------------------------

    if "season_encoded" in working.columns:

        working["season_encoded"] = pd.to_numeric(
            working["season_encoded"],
            errors="coerce",
        )

    else:

        month = None

        if "month" in working.columns:

            month = pd.to_numeric(
                working["month"],
                errors="coerce",
            )

        else:

            datetime_column = _find_first_column(
                working,
                [
                    "detection_timestamp",
                    "acq_datetime",
                    "datetime",
                    "timestamp",
                    "date_time",
                ],
            )

            if datetime_column is not None:

                parsed_datetime = pd.to_datetime(
                    working[datetime_column],
                    errors="coerce",
                )

                month = parsed_datetime.dt.month

        if month is None:

            working["season_encoded"] = -1

        else:

            working["season_encoded"] = np.select(
                [
                    month.isin([12, 1, 2]),
                    month.isin([3, 4, 5]),
                    month.isin([6, 7, 8]),
                    month.isin([9, 10, 11]),
                ],
                [
                    0,
                    1,
                    2,
                    3,
                ],
                default=-1,
            )

    # ------------------------------------------------------------------------
    # Final fixed feature matrix
    # ------------------------------------------------------------------------

    missing_features = [
        column
        for column in FEATURE_COLUMNS
        if column not in working.columns
    ]

    if missing_features:
        raise ValueError(
            "Could not prepare required features: "
            + ", ".join(missing_features)
        )

    features = working.loc[:, FEATURE_COLUMNS].copy()

    # Convert every feature to numeric.
    for column in FEATURE_COLUMNS:

        features[column] = pd.to_numeric(
            features[column],
            errors="coerce",
        )

    if features.isna().any().any():

        nan_columns = (
            features.columns[
                features.isna().any()
            ]
            .tolist()
        )

        raise ValueError(
            "Prepared feature matrix contains missing/invalid values in: "
            + ", ".join(nan_columns)
        )

    if not np.isfinite(
        features.to_numpy(dtype=float)
    ).all():

        raise ValueError(
            "Prepared feature matrix contains non-finite values."
        )

    return features


