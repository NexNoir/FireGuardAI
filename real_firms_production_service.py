def _find_first_column(
    dataframe: pd.DataFrame,
    candidates: Iterable[str],
) -> Union[str, None]:
    """
    Return the first existing column name from candidates.
    """

    for column in candidates:
        if column in dataframe.columns:
            return column

    return None


def _normalize_text(series: pd.Series) -> pd.Series:
    """
    Normalize text safely without modifying the source dataframe.
    """

    return (
        series.astype(str)
        .fillna("")
        .str.strip()
        .str.upper()
    )


def _encode_categorical(
    series: pd.Series,
    mapping: Dict[str, int],
    default_value: int = -1,
) -> pd.Series:
    """
    Convert known categorical values to stable integer codes.

    Unknown values receive default_value.
    """

    normalized = _normalize_text(series)

    return (
        normalized.map(mapping)
        .fillna(default_value)
        .astype(int)
    )


def _extract_model(saved_object: Any) -> Any:
    """
    Extract the actual sklearn-compatible model from a saved object.

    Existing training artifacts may contain either:
        - the model directly
        - a dictionary containing the model

    No saved object is modified.
    """

    if hasattr(saved_object, "predict_proba"):
        return saved_object

    if isinstance(saved_object, dict):

        preferred_keys = [
            "model",
            "pipeline",
            "estimator",
            "classifier",
        ]

        for key in preferred_keys:

            candidate = saved_object.get(key)

            if hasattr(candidate, "predict_proba"):
                return candidate

        for value in saved_object.values():

            if hasattr(value, "predict_proba"):
                return value

    raise TypeError(
        "Could not find a prediction model with predict_proba() "
        f"inside saved object of type: {type(saved_object).__name__}"
    )


def _extract_thresholds(config: Dict[str, Any]) -> Dict[str, float]:
    """
    Extract approved thresholds from the existing configuration.

    Supports the structure generated by the previous FIREGUARD threshold
    configuration script.
    """

    threshold_source = config.get("thresholds", config)

    aliases = {
        "24h": ["24h", "24H", "fire_next_24h"],
        "48h": ["48h", "48H", "fire_next_48h"],
        "72h": ["72h", "72H", "fire_next_72h"],
    }

    thresholds: Dict[str, float] = {}

    for horizon, keys in aliases.items():

        value = None

        for key in keys:

            if key in threshold_source:
                value = threshold_source[key]
                break

        if isinstance(value, dict):

            for nested_key in ["threshold", "value"]:

                if nested_key in value:
                    value = value[nested_key]
                    break

        if value is None:
            raise KeyError(
                f"Threshold for {horizon} not found in configuration."
            )

        try:
            value = float(value)
        except (TypeError, ValueError) as error:
            raise ValueError(
                f"Invalid threshold for {horizon}: {value!r}"
            ) from error

        if not 0.0 <= value <= 1.0:
            raise ValueError(
                f"Threshold for {horizon} must be between 0 and 1. "
                f"Received: {value}"
            )

        thresholds[horizon] = value

    return thresholds


