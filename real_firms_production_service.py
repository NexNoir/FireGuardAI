class RealFirmsProductionService:
    """
    Reusable production inference service.

    Models and thresholds are loaded during initialization and reused for
    subsequent predictions.
    """

    def __init__(
        self,
        model_dir: Union[str, Path] = MODEL_DIR,
        threshold_config_path: Union[str, Path] = THRESHOLD_CONFIG_PATH,
    ) -> None:

        self.model_dir = Path(model_dir)
        self.threshold_config_path = Path(threshold_config_path)

        self.model_files = {
            "24h": self.model_dir
            / "fireguard_real_firms_sensor_only_24h_v1.joblib",

            "48h": self.model_dir
            / "fireguard_real_firms_sensor_only_48h_v1.joblib",

            "72h": self.model_dir
            / "fireguard_real_firms_sensor_only_72h_v1.joblib",
        }

        self.models: Dict[str, Any] = {}

        self.thresholds: Dict[str, float] = {}

        self._load_thresholds()
        self._load_models()
        self._validate_model_schemas()

    # ------------------------------------------------------------------------

    def _load_thresholds(self) -> None:

        if not self.threshold_config_path.exists():

            raise FileNotFoundError(
                "Threshold configuration not found: "
                f"{self.threshold_config_path}"
            )

        with open(
            self.threshold_config_path,
            "r",
            encoding="utf-8",
        ) as file:

            config = json.load(file)

        self.thresholds = _extract_thresholds(config)

    # ------------------------------------------------------------------------

    def _load_models(self) -> None:

        for horizon, model_path in self.model_files.items():

            if not model_path.exists():

                raise FileNotFoundError(
                    f"{horizon} model not found: {model_path}"
                )

            saved_object = joblib.load(model_path)

            model = _extract_model(saved_object)

            self.models[horizon] = model

    # ------------------------------------------------------------------------

    def _validate_model_schemas(self) -> None:
        """
        Basic feature-count validation against the approved schema.
        """

        expected_count = len(FEATURE_COLUMNS)

        for horizon, model in self.models.items():

            model_feature_count = None

            if hasattr(model, "n_features_in_"):
                model_feature_count = int(
                    model.n_features_in_
                )

            elif hasattr(model, "feature_names_in_"):
                model_feature_count = len(
                    model.feature_names_in_
                )

            if (
                model_feature_count is not None
                and model_feature_count != expected_count
            ):
                raise ValueError(
                    f"{horizon} model expects "
                    f"{model_feature_count} features, "
                    f"but production schema contains "
                    f"{expected_count}."
                )

    # ------------------------------------------------------------------------

    @property
    def feature_columns(self) -> List[str]:
        """
        Return the approved feature order.
        """

        return FEATURE_COLUMNS.copy()

    # ------------------------------------------------------------------------

    def predict(
        self,
        dataframe: pd.DataFrame,
    ) -> pd.DataFrame:
        """
        Run production inference.

        Returns a copy of the input dataframe with:
            prob_24h
            pred_24h
            prob_48h
            pred_48h
            prob_72h
            pred_72h

        The original dataframe is never modified.
        """

        features = prepare_real_firms_features(dataframe)

        result = dataframe.copy()

        for horizon in ["24h", "48h", "72h"]:

            model = self.models[horizon]

            threshold = self.thresholds[horizon]

            probabilities = model.predict_proba(
                features
            )[:, 1]

            probabilities = np.asarray(
                probabilities,
                dtype=float,
            )

            if not np.isfinite(probabilities).all():

                raise ValueError(
                    f"{horizon} model produced non-finite probabilities."
                )

            if (
                probabilities.min() < 0.0
                or probabilities.max() > 1.0
            ):
                raise ValueError(
                    f"{horizon} model produced probabilities "
                    "outside [0, 1]."
                )

            predictions = (
                probabilities >= threshold
            ).astype(int)

            result[f"prob_{horizon}"] = probabilities

            result[f"pred_{horizon}"] = predictions

        return result

    # ------------------------------------------------------------------------

    def predict_record(
        self,
        record: Dict[str, Any],
    ) -> Dict[str, Any]:
        """
        Run production inference for one record.
        """

        input_dataframe = pd.DataFrame([record])

        result = self.predict(input_dataframe)

        output_columns = [
            "prob_24h",
            "pred_24h",
            "prob_48h",
            "pred_48h",
            "prob_72h",
            "pred_72h",
        ]

        return {
            column: (
                float(result.iloc[0][column])
                if column.startswith("prob_")
                else int(result.iloc[0][column])
            )
            for column in output_columns
        }

    # ------------------------------------------------------------------------

    def get_status(self) -> Dict[str, Any]:
        """
        Return service metadata without changing any model or dataset.
        """

        return {
            "status": "ready",
            "project": "FIREGUARD",
            "service": "REAL FIRMS PRODUCTION SERVICE V1",
            "feature_count": len(FEATURE_COLUMNS),
            "feature_columns": FEATURE_COLUMNS.copy(),
            "thresholds": self.thresholds.copy(),
            "models": {
                horizon: str(path)
                for horizon, path
                in self.model_files.items()
            },
            "retraining": False,
            "model_modification": False,
            "dataset_modification": False,
            "synthetic_data": False,
            "fabricated_labels": False,
        }


