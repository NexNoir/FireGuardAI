# SINGLETON HELPER
# ============================================================================

_default_service: Union[
    RealFirmsProductionService,
    None,
] = None


def get_production_service() -> RealFirmsProductionService:
    """
    Return a cached production service instance.

    Models are loaded only once per Python process.
    """

    global _default_service

    if _default_service is None:

        _default_service = RealFirmsProductionService()

    return _default_service


def run_production_inference(
    dataframe: pd.DataFrame,
) -> pd.DataFrame:
    """
    Convenience function for application/API integration.
    """

    service = get_production_service()

    return service.predict(dataframe)


def run_production_inference_record(
    record: Dict[str, Any],
) -> Dict[str, Any]:
    """
    Convenience function for one-record inference.
    """

    service = get_production_service()

    return service.predict_record(record)


